use crate::field::{FieldInfo, FilterMapField, StructField};
use crate::parse_attrs::By;
use proc_macro2::TokenStream;
use quote::{ToTokens, format_ident, quote};
use syn::{ExprPath, Ident};

/// Generate the venndb logic
pub fn generate_db(
    name: &Ident,
    name_db: &Ident,
    validator: Option<&ExprPath>,
    vis: &syn::Visibility,
    fields: &[StructField],
) -> TokenStream {
    let fields: Vec<_> = fields.iter().filter_map(StructField::info).collect();

    let db_error = DbError::new(validator, &fields[..]);

    let db_struct = generate_db_struct(name, name_db, vis, &fields[..]);
    let db_struct_methods =
        generate_db_struct_methods(name, name_db, validator, vis, &db_error, &fields[..]);

    let db_query = generate_query_struct(name, name_db, vis, &fields[..]);

    let db_error_definitions = db_error.generate_definitions(name_db, vis);

    quote! {
        #db_struct

        #db_struct_methods

        #db_query

        #db_error_definitions
    }
}

/// The type of the values a filter map is queried with.
fn value_ty(field: &FilterMapField) -> TokenStream {
    let ty = field.ty;
    match (field.set, field.item) {
        (None, _) => quote! { #ty },
        (Some(By::Trait), _) => quote! { <#ty as ::venndb::FilterSet>::Item },
        (Some(By::Path(_)), Some(item)) => quote! { #item },
        (Some(By::Path(_)), None) => unreachable!("checked when the field is parsed"),
    }
}

fn generate_db_struct(
    name: &Ident,
    name_db: &Ident,
    vis: &syn::Visibility,
    fields: &[FieldInfo],
) -> TokenStream {
    let db_fields: Vec<_> = fields
        .iter()
        .map(|info| match info {
            FieldInfo::Key(field) => {
                let column = field.column_name();
                let ty = field.ty;
                quote! {
                    #column: ::venndb::KeyIndex<#ty>,
                }
            }
            FieldInfo::Filter(field) => {
                let column = field.column_name();
                quote! {
                    #column: ::venndb::BoolColumn,
                }
            }
            FieldInfo::FilterMap(field) => {
                let column = field.column_name();
                let ty = value_ty(field);
                quote! {
                    #column: ::venndb::ValueColumn<#ty>,
                }
            }
        })
        .collect();

    let db_doc = format!(
        "An in-memory database for storing instances of [`{}`], generated by `#[derive(VennDB)]`.",
        name
    );
    quote! {
        #[doc=#db_doc]
        #[derive(Debug, Default)]
        #vis struct #name_db {
            rows: Vec<#name>,
            #(#db_fields)*
        }
    }
}

fn generate_db_struct_methods(
    name: &Ident,
    name_db: &Ident,
    validator: Option<&ExprPath>,
    vis: &syn::Visibility,
    db_error: &DbError,
    fields: &[FieldInfo],
) -> TokenStream {
    let method_new = generate_db_struct_method_new(name, vis, fields);
    let method_from_rows = generate_db_struct_method_from_rows(name, name_db, vis, db_error);
    let field_methods = generate_db_struct_field_methods(name, vis, fields);
    let method_append =
        generate_db_struct_method_append(name, name_db, validator, vis, db_error, fields);

    let shrink_columns: Vec<_> = fields
        .iter()
        .filter_map(|info| match info {
            FieldInfo::Key(_) => None,
            FieldInfo::Filter(field) => Some(field.column_name()),
            FieldInfo::FilterMap(field) => Some(field.column_name()),
        })
        .collect();

    let method_get_doc = format!("Get an instance of [`{}`] by its row index.", name);
    let method_column_doc = format!(
        "The rows of the instances of [`{}`] matching the predicate, \
         to filter a query on with [`Filter::Is`](::venndb::Filter::Is) \
         or [`Filter::Not`](::venndb::Filter::Not).",
        name
    );

    quote! {
        #[allow(clippy::unused_unit)]
        impl #name_db {
            #method_new

            #method_from_rows

            /// Return the number of rows in the database.
            #vis fn len(&self) -> usize {
                self.rows.len()
            }

            /// Return the capacity of the database,
            /// which is automatically grown as needed.
            #vis fn capacity(&self) -> usize {
                self.rows.capacity()
            }

            /// Return `true` if the database is empty.
            #vis fn is_empty(&self) -> bool {
                self.rows.is_empty()
            }

            /// Return an iterator over the rows in the database.
            #vis fn iter(&self) -> impl ::std::iter::Iterator<Item = &#name> {
                self.rows.iter()
            }

            #[doc=#method_get_doc]
            #vis fn get(&self, index: usize) -> ::std::option::Option<&#name> {
                self.rows.get(index)
            }

            #[doc=#method_column_doc]
            ///
            /// Rows appended afterwards are not part of it.
            #vis fn column(&self, mut predicate: impl ::std::ops::FnMut(&#name) -> bool) -> ::venndb::RowSet {
                self.rows
                    .iter()
                    .enumerate()
                    .filter(|(_, row)| predicate(row))
                    .map(|(index, _)| index)
                    .collect()
            }

            /// A column to set rows in while the database is in use, to filter a query on
            /// with [`Filter::Runtime`](::venndb::Filter::Runtime).
            ///
            /// Rows appended afterwards are not part of it.
            #vis fn runtime_column(&self) -> ::venndb::RuntimeColumn {
                ::venndb::RuntimeColumn::new(self.rows.len())
            }

            /// Release the memory the database does not need.
            #vis fn shrink_to_fit(&mut self) {
                self.rows.shrink_to_fit();
                #(self.#shrink_columns.shrink_to_fit();)*
            }

            #field_methods

            #method_append

            /// Consumes the database and returns the rows.
            #vis fn into_rows(self) -> ::std::vec::Vec<#name> {
                self.rows
            }
        }
    }
}

fn generate_db_struct_method_new(
    name: &Ident,
    vis: &syn::Visibility,
    fields: &[FieldInfo],
) -> TokenStream {
    let method_doc = format!(
        "Construct a new empty database for storing instances of [`{}`].",
        name
    );
    let method_capacity_doc = format!(
        "Construct a new empty database for storing instances of [`{}`] with a given capacity.",
        name
    );

    let keys: Vec<_> = fields
        .iter()
        .filter_map(|info| match info {
            FieldInfo::Key(field) => Some(field.column_name()),
            FieldInfo::Filter(_) | FieldInfo::FilterMap(_) => None,
        })
        .collect();

    quote! {
        #[doc=#method_doc]
        #vis fn new() -> Self {
            Self::default()
        }

        #[doc=#method_capacity_doc]
        #vis fn with_capacity(capacity: usize) -> Self {
            Self {
                rows: ::std::vec::Vec::with_capacity(capacity),
                #(#keys: ::venndb::KeyIndex::with_capacity(capacity),)*
                ..Self::default()
            }
        }
    }
}

fn generate_db_struct_method_from_rows(
    name: &Ident,
    name_db: &Ident,
    vis: &syn::Visibility,
    db_error: &DbError,
) -> TokenStream {
    let method_doc = format!(
        "Construct a new database from the given set of [`{}`] rows.",
        name
    );

    let method_iter_doc = format!(
        "Construct a new database from the given iterator of items that can be turned into [`{}`] instances.",
        name
    );

    let return_type =
        db_error.generate_fn_output(name_db, quote! { ::std::vec::Vec<#name> }, quote! { Self });
    let append_internal_call = db_error.generate_fn_error_kind_usage(
        name_db,
        quote! {
            db.append_internal(row, index)
        },
        quote! {
            rows
        },
    );
    let fn_result = db_error.generate_fn_return_value_ok(quote! { db });

    quote! {
        #[doc=#method_doc]
        #vis fn from_rows(rows: ::std::vec::Vec<#name>) -> #return_type {
            let mut db = Self::with_capacity(0);
            for (index, row) in rows.iter().enumerate() {
                #append_internal_call
            }
            db.rows = rows;
            db.shrink_to_fit();
            #fn_result
        }

        #[doc=#method_iter_doc]
        #vis fn from_iter<I, Item>(iter: I) -> #return_type
            where
                I: ::std::iter::IntoIterator<Item = Item>,
                Item: ::std::convert::Into<#name>,
        {
            let rows: ::std::vec::Vec<#name> = iter.into_iter().map(::std::convert::Into::into).collect();
            Self::from_rows(rows)
        }
    }
}

fn generate_db_struct_method_append(
    name: &Ident,
    name_db: &Ident,
    validator: Option<&ExprPath>,
    vis: &syn::Visibility,
    db_error: &DbError,
    fields: &[FieldInfo],
) -> TokenStream {
    let method_doc = format!("Append a new instance of [`{}`] to the database.", name);
    let method_iter_doc = format!(
        "Extend the database with the given iterator of items that can be turned into [`{}`] instances.",
        name
    );

    let validator_check = match validator {
        Some(validator) => {
            let err = DbError::generate_invalid_row_error_kind_creation(name_db);
            quote! {
                if !#validator(__venndb_row) {
                    return Err(#err);
                }
            }
        }
        None => quote! {},
    };

    // keys are all checked before anything is added, to never add half a row
    let db_field_insert_checks: Vec<_> = fields
        .iter()
        .filter_map(|info| match info {
            FieldInfo::Key(field) => {
                let column = field.column_name();
                let field_name = field.name;
                let key = match field.with {
                    Some(with) => quote! { #with(__venndb_row) },
                    None => quote! { ::std::clone::Clone::clone(&__venndb_row.#field_name) },
                };
                let key_name = format_ident!("__venndb_{}", column);
                let db_duplicate_error_kind_creation =
                    DbError::generate_duplicate_key_error_kind_creation(name_db);

                Some(quote! {
                    let #key_name = #key;
                    if self.#column.contains(&#key_name) {
                        return Err(#db_duplicate_error_kind_creation);
                    }
                })
            }
            FieldInfo::Filter(_) | FieldInfo::FilterMap(_) => None,
        })
        .collect();

    let db_field_insert_commits: Vec<_> = fields
        .iter()
        .map(|info| match info {
            FieldInfo::Key(field) => {
                let column = field.column_name();
                let key_name = format_ident!("__venndb_{}", column);
                quote! {
                    self.#column.insert(#key_name, __venndb_index);
                }
            }
            FieldInfo::Filter(field) => {
                let name = field.name;
                let column = field.column_name();
                if field.optional {
                    quote! {
                        self.#column.push(__venndb_row.#name);
                    }
                } else {
                    quote! {
                        self.#column.push(::std::option::Option::Some(__venndb_row.#name));
                    }
                }
            }
            FieldInfo::FilterMap(field) => {
                let name = field.name;
                let column = field.column_name();
                let any_fn = field.any_fn_name();
                let push = match (field.set, field.any) {
                    (Some(By::Trait), _) => quote! {
                        ::venndb::FilterSet::for_each_member(__venndb_value, |__venndb_member| {
                            self.#column.push(__venndb_index, __venndb_member);
                        });
                    },
                    (Some(By::Path(members)), _) => quote! {
                        for __venndb_member in #members(__venndb_value) {
                            self.#column.push(
                                __venndb_index,
                                ::std::borrow::Borrow::borrow(&__venndb_member),
                            );
                        }
                    },
                    (None, Some(_)) => quote! {
                        if Self::#any_fn(__venndb_value) {
                            self.#column.push_any(__venndb_index);
                        } else {
                            self.#column.push(__venndb_index, __venndb_value);
                        }
                    },
                    (None, None) => quote! {
                        self.#column.push(__venndb_index, __venndb_value);
                    },
                };
                if field.optional {
                    quote! {
                        if let ::std::option::Option::Some(__venndb_value) = &__venndb_row.#name {
                            #push
                        }
                    }
                } else {
                    quote! {
                        {
                            let __venndb_value = &__venndb_row.#name;
                            #push
                        }
                    }
                }
            }
        })
        .collect();

    // the functions of the user are called where no name of ours is in their way
    let any_fns: Vec<_> = fields
        .iter()
        .filter_map(|info| match info {
            FieldInfo::FilterMap(field) => {
                let any_fn = field.any_fn_name();
                let ty = field.ty;
                let is_any = match field.any? {
                    By::Trait => quote! { ::venndb::Any::is_any(__venndb_value) },
                    By::Path(is_any) => quote! { #is_any(__venndb_value) },
                };
                Some(quote! {
                    #[doc(hidden)]
                    #[inline]
                    fn #any_fn(__venndb_value: &#ty) -> bool {
                        #is_any
                    }
                })
            }
            FieldInfo::Key(_) | FieldInfo::Filter(_) => None,
        })
        .collect();

    let append_return_type = db_error.generate_fn_output(name_db, quote! { #name }, quote! { () });
    let extend_return_type =
        db_error.generate_fn_output(name_db, quote! { (#name, I::IntoIter) }, quote! { () });
    let append_kind_return_type = db_error.generate_fn_kind_output(name_db, quote! { () });

    let append_internal_call = db_error.generate_fn_error_kind_usage(
        name_db,
        quote! {
            self.append_internal(&data, index)
        },
        quote! { data },
    );

    let extend_append_internal_call = db_error.generate_fn_error_kind_usage(
        name_db,
        quote! {
            self.append_internal(&data, index)
        },
        quote! { (data, iter) },
    );

    let append_return_output = db_error.generate_fn_return_value_ok(quote! { () });

    quote! {
        #[doc=#method_doc]
        #vis fn append(&mut self, data: impl ::std::convert::Into<#name>) -> #append_return_type {
            let index = self.rows.len();
            let data = data.into();
            #append_internal_call
            self.rows.push(data);
            #append_return_output
        }

        #[doc=#method_iter_doc]
        #vis fn extend<I, Item>(&mut self, iter: I) -> #extend_return_type
            where
                I: ::std::iter::IntoIterator<Item = Item>,
                Item: ::std::convert::Into<#name>,
        {
            let mut index = self.rows.len();
            let mut iter = iter.into_iter();
            for item in &mut iter {
                let data = item.into();
                #extend_append_internal_call
                self.rows.push(data);
                index += 1;
            }
            #append_return_output
        }

        #(#any_fns)*

        fn append_internal(&mut self, __venndb_row: &#name, __venndb_index: usize) -> #append_kind_return_type {
            assert!(
                __venndb_index < ::venndb::RowSet::MAX_ROWS,
                "venndb: a database holds at most u32::MAX rows"
            );
            #validator_check
            #(#db_field_insert_checks)*
            #(#db_field_insert_commits)*
            #append_return_output
        }
    }
}

fn generate_db_struct_field_methods(
    name: &Ident,
    vis: &syn::Visibility,
    fields: &[FieldInfo],
) -> TokenStream {
    let db_key_methods: Vec<_> = fields
        .iter()
        .filter_map(|info| match info {
            FieldInfo::Key(field) => {
                let column = field.column_name();
                let ty = field.ty;
                let method_name = field.method_name();
                let index_method_name = field.index_method_name();
                let doc = format!(
                    "Get an instance of [`{}`] by its key `{}`, if it exists in the database.",
                    name, field.name
                );
                let index_doc = format!(
                    "Get the row index of an instance of [`{}`] by its key `{}`, if it exists in the database.",
                    name, field.name
                );
                Some(quote! {
                    #[doc=#doc]
                    #vis fn #method_name<Q>(&self, key: &Q) -> ::std::option::Option<&#name>
                        where
                            #ty: ::std::borrow::Borrow<Q>,
                            Q: ::std::hash::Hash + ::std::cmp::Eq + ?::std::marker::Sized,
                    {
                        self.#column.get(key).and_then(|index| self.rows.get(index))
                    }

                    #[doc=#index_doc]
                    #vis fn #index_method_name<Q>(&self, key: &Q) -> ::std::option::Option<usize>
                        where
                            #ty: ::std::borrow::Borrow<Q>,
                            Q: ::std::hash::Hash + ::std::cmp::Eq + ?::std::marker::Sized,
                    {
                        self.#column.get(key)
                    }
                })
            }
            FieldInfo::Filter(_) | FieldInfo::FilterMap(_) => None,
        })
        .collect();

    quote! {
        #(#db_key_methods)*
    }
}

fn generate_query_struct(
    name: &Ident,
    name_db: &Ident,
    vis: &syn::Visibility,
    fields: &[FieldInfo],
) -> TokenStream {
    let name_query = format_ident!("{}Query", name_db);
    let name_query_result = format_ident!("{}Result", name_query);

    // every filter has its own slot in the plan of a query
    let mut slots = 0usize;
    let filter_setters: Vec<_> = fields
        .iter()
        .filter_map(|info| match info {
            FieldInfo::Filter(field) => {
                let name = field.name;
                let column = field.column_name();
                let slot = slots;
                slots += 1;
                let doc = format!("Enable and set the `{}` filter.", name);
                Some(quote! {
                    #[doc=#doc]
                    #vis fn #name(&mut self, value: bool) -> &mut Self {
                        self.db.#column.filter(&mut self.plan, #slot, value);
                        self
                    }
                })
            }
            FieldInfo::FilterMap(field) => {
                let name = field.name;
                let name_where = field.where_method_name();
                let column = field.column_name();
                let ty = value_ty(field);
                let slot = slots;
                slots += 1;
                let any_fn = field.any_fn_name();
                let is_any = match field.any {
                    Some(_) => quote! { #name_db::#any_fn(&value) },
                    None => quote! { false },
                };
                let doc = format!(
                    "Enable and set the `{}` filter-map with the given option.",
                    name
                );
                let doc_where = format!(
                    "Filter on the values of `{}` for which the predicate returns `true`.",
                    name
                );
                Some(quote! {
                    #[doc=#doc]
                    #vis fn #name(&mut self, value: impl ::std::convert::Into<#ty>) -> &mut Self {
                        let value: #ty = value.into();
                        let any = #is_any;
                        self.db.#column.filter(&mut self.plan, #slot, &value, any);
                        self
                    }

                    #[doc=#doc_where]
                    ///
                    /// The predicate is called once per distinct value, not once per row.
                    #vis fn #name_where(&mut self, predicate: impl ::std::ops::FnMut(&#ty) -> bool) -> &mut Self {
                        self.db.#column.filter_where(&mut self.plan, predicate);
                        self
                    }
                })
            }
            FieldInfo::Key(_) => None,
        })
        .collect();

    let query_doc = format!(
        "A query object for filtering instances of [`{}`], within [`{}`], generated by `#[derive(VennDB)]`.",
        name, name_db
    );

    let query_method_doc = format!(
        "Return a new [`{}`] for filtering instances of [`{}`].",
        name_query, name
    );

    let name_query_result_doc = format!(
        "Contains a reference to the found instances of [`{}`] if there is at least one found, queried using [`{}`], generated by `#[derive(VennDB)]`.",
        name, name_query
    );

    let query_result_method_doc_first = format!(
        "Return the first instance of [`{}`] found by the query.",
        name
    );
    let query_result_method_doc_any = format!(
        "Return a random instance of [`{}`] found by the query.",
        name
    );
    let query_result_method_doc_any_where = format!(
        "Return a random instance of [`{}`] found by the query, for which the predicate returns `true`.",
        name
    );
    let query_result_method_doc_iter = format!(
        "Return an iterator over the instances of [`{}`] found by the query.",
        name
    );

    quote! {
        #[doc=#query_doc]
        #[derive(Debug)]
        #vis struct #name_query<'a> {
            db: &'a #name_db,
            plan: ::venndb::Plan<'a>,
        }

        impl<'a> #name_query<'a> {
            #(#filter_setters)*

            /// Add a filter on a column that is not part of the database,
            /// such as a [`RuntimeColumn`](::venndb::RuntimeColumn).
            #vis fn and(&mut self, filter: ::venndb::Filter<'a>) -> &mut Self {
                self.plan.and(filter);
                self
            }

            /// Reset the query to its initial values.
            #vis fn reset(&mut self) -> &mut Self {
                self.plan.reset();
                self
            }

            /// Execute the query on the database, returning an iterator over the results.
            #vis fn execute(&self) -> Option<#name_query_result<'a>> {
                self.plan.execute().map(|matches| #name_query_result {
                    rows: &self.db.rows,
                    matches,
                })
            }
        }

        impl #name_db {
            #[doc=#query_method_doc]
            #vis fn query(&self) -> #name_query<'_> {
                #name_query {
                    db: self,
                    plan: ::venndb::Plan::new(self.rows.len(), #slots),
                }
            }
        }

        #[doc=#name_query_result_doc]
        #[derive(Debug)]
        #vis struct #name_query_result<'a> {
            rows: &'a [#name],
            matches: ::venndb::Matches<'a>,
        }

        #[allow(clippy::len_without_is_empty)]
        impl<'a> #name_query_result<'a> {
            /// Return the number of instances found by the query, never zero.
            #vis fn len(&self) -> usize {
                self.matches.len()
            }

            #[doc=#query_result_method_doc_first]
            #vis fn first(&self) -> &'a #name {
                &self.rows[self.matches.first()]
            }

            #[doc=#query_result_method_doc_any]
            #vis fn any(&self) -> &'a #name {
                &self.rows[self.matches.random()]
            }

            #[doc=#query_result_method_doc_any_where]
            ///
            /// Cheaper than [`Self::filter`] followed by [`Self::any`],
            /// as long as the predicate is not rarely `true`.
            #vis fn any_where(&self, mut predicate: impl ::std::ops::FnMut(&#name) -> bool) -> ::std::option::Option<&'a #name> {
                self.matches
                    .random_where(|index| predicate(&self.rows[index]))
                    .map(|index| &self.rows[index])
            }

            #[doc=#query_result_method_doc_iter]
            #vis fn iter(&self) -> impl ::std::iter::Iterator<Item = &'a #name> + '_ {
                self.matches.iter().map(|index| &self.rows[index])
            }

            /// Filter the found results with the given predicate.
            #vis fn filter(&self, mut predicate: impl ::std::ops::FnMut(&#name) -> bool) -> Option<#name_query_result<'a>> {
                self.matches
                    .filter(|index| predicate(&self.rows[index]))
                    .map(|matches| #name_query_result {
                        rows: self.rows,
                        matches,
                    })
            }
        }
    }
}

#[derive(Debug)]
/// Used to generate the optional error logic,
/// which we only which to generate in case operations are possible to fail.
///
/// Example: duplicate key, in case a key field is used
struct DbError {
    error_kinds: Vec<DbErrorKind>,
}

#[derive(Debug)]
enum DbErrorKind {
    DuplicateKey,
    InvalidRow,
}

impl ToTokens for DbErrorKind {
    fn to_tokens(&self, tokens: &mut TokenStream) {
        match self {
            Self::DuplicateKey => {
                tokens.extend(quote! {
                    /// The error kind for when the row to be insired has a key already known (key duplicate).
                    DuplicateKey,
                });
            }
            Self::InvalidRow => {
                tokens.extend(quote! {
                    /// The error kind for when the row to be inserted is invalid.
                    InvalidRow,
                });
            }
        }
    }
}

impl DbError {
    fn new(validator: Option<&ExprPath>, fields: &[FieldInfo]) -> Self {
        let mut error_kinds = Vec::new();

        if validator.is_some() {
            error_kinds.push(DbErrorKind::InvalidRow);
        }

        if fields.iter().any(|info| matches!(info, FieldInfo::Key(_))) {
            error_kinds.push(DbErrorKind::DuplicateKey);
        }

        Self { error_kinds }
    }

    fn generate_duplicate_key_error_kind_creation(name_db: &Ident) -> TokenStream {
        let ident_error_kind = format_ident!("{}ErrorKind", name_db);
        quote! {
            #ident_error_kind::DuplicateKey
        }
    }

    fn generate_invalid_row_error_kind_creation(name_db: &Ident) -> TokenStream {
        let ident_error_kind = format_ident!("{}ErrorKind", name_db);
        quote! {
            #ident_error_kind::InvalidRow
        }
    }

    fn generate_fn_error_kind_usage(
        &self,
        name_db: &Ident,
        original: TokenStream,
        input: TokenStream,
    ) -> TokenStream {
        if self.error_kinds.is_empty() {
            return quote! {
                #original;
            };
        }

        let ident_error = format_ident!("{}Error", name_db);

        quote! {
            if let Err(kind) = #original {
                return Err(#ident_error::new(kind, #input, index));
            }
        }
    }

    fn generate_fn_return_value_ok(&self, output: TokenStream) -> TokenStream {
        if self.error_kinds.is_empty() {
            return output;
        }
        quote! {
            Ok(#output)
        }
    }

    fn generate_fn_output(
        &self,
        name_db: &Ident,
        input: TokenStream,
        original: TokenStream,
    ) -> TokenStream {
        if self.error_kinds.is_empty() {
            return original;
        }

        let ident_error = format_ident!("{}Error", name_db);
        quote! {
            Result<#original, #ident_error<#input>>
        }
    }

    fn generate_fn_kind_output(&self, name_db: &Ident, original: TokenStream) -> TokenStream {
        if self.error_kinds.is_empty() {
            return original;
        }

        let ident_error_kind = format_ident!("{}ErrorKind", name_db);
        quote! {
            Result<#original, #ident_error_kind>
        }
    }

    fn generate_definitions(&self, name_db: &Ident, vis: &syn::Visibility) -> TokenStream {
        if self.error_kinds.is_empty() {
            return TokenStream::new();
        }

        let ident_error = format_ident!("{}Error", name_db);
        let ident_error_kind = format_ident!("{}Kind", ident_error);
        let ident_error_debug = format!("{}", ident_error);

        let error_kinds = &self.error_kinds;

        let doc_error_kind = format!(
            "The kind of error that occurred when appending a row to the [`{}`].",
            name_db
        );
        let doc_error = format!(
            "The error type that can be returned when appending a row to the [`{}`].",
            name_db
        );
        let doc_error_kind_method = format!(
            "The [`{}`] that occurred when appending a row to the [`{}`].",
            ident_error_kind, name_db
        );

        quote! {
            #[derive(Debug, PartialEq, Eq, Clone, Copy)]
            #[doc = #doc_error_kind]
            #vis enum #ident_error_kind {
                #(#error_kinds)*
            }

            #[doc = #doc_error]
            #vis struct #ident_error<T> {
                kind: #ident_error_kind,
                input: T,
                row_index: usize,
            }

            impl<T> ::std::fmt::Debug for #ident_error<T> {
                fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
                    f.debug_struct(#ident_error_debug)
                        .field("kind", &self.kind)
                        .field("row_index", &self.row_index)
                        .finish()
                }
            }

            impl<T> #ident_error<T> {
                /// Create a new error.
                fn new(kind: #ident_error_kind, input: T, row_index: usize) -> Self {
                    Self {
                        kind,
                        input,
                        row_index,
                    }
                }

                #[doc = #doc_error_kind_method]
                #vis fn kind(&self) -> #ident_error_kind {
                        self.kind
                }

                /// Return a reference to the input that caused the error.
                #vis fn input(&self) -> &T {
                    &self.input
                }

                /// Consume this error and return the input that caused the error.
                #vis fn into_input(self) -> T {
                    self.input
                }

                /// Return the index of the row that caused the error.
                #vis fn row_index(&self) -> usize {
                    self.row_index
                }
            }

            impl<T> ::std::fmt::Display for #ident_error<T> {
                fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
                    write!(f, "{}: {:?}", #ident_error_debug, self.kind)
                }
            }

            impl<T> ::std::error::Error for #ident_error<T> {}
        }
    }
}
